"""Liquidation-level model on hand-made bars."""
import numpy as np
import pandas as pd
import pytest

from src.indicators import liquidations as lq


def bars(rows):
    idx = pd.date_range("2026-10-27", periods=len(rows), freq="5min", tz="UTC")
    return pd.DataFrame(rows, columns=["h", "l", "c", "oi", "buy", "sell"], index=idx)


def test_levels_placed_at_leverage_prices():
    b = bars([[100, 100, 100, 1000, 1, 1], [100, 100, 100, 1100, 1, 1], [100, 100, 100, 1100, 1, 1]])
    out = lq.liquidation_levels(b, step=0.1)
    total = 100 * 100                     # 100 coins at $100
    assert out["long"].sum() + out["short"].sum() == pytest.approx(total)
    p = out["prices"]
    near = lambda side, px: out[side][abs(p - px) < 0.15].sum()  # noqa: E731 - bucket edges round either way
    assert near("long", 100 * (1 - 0.1 + lq.MMR)) == pytest.approx(total * 0.5 * lq.LEVERAGE[10])
    assert near("short", 100 * (1 + 0.01 - lq.MMR)) == pytest.approx(total * 0.5 * lq.LEVERAGE[100])


def test_taker_split_and_sweep():
    b = bars([[100, 100, 100, 1000, 3, 1], [100, 100, 100, 1100, 3, 1],
              [100, 98, 99, 1100, 1, 1]])          # low 98 wipes the 100x and 50x long levels
    out = lq.liquidation_levels(b, step=0.1)
    usd = 100 * 100
    assert out["short"].sum() == pytest.approx(usd * 0.25)
    assert out["long"].sum() == pytest.approx(usd * 0.75 * (lq.LEVERAGE[10] + lq.LEVERAGE[25]))


def test_closing_shrinks_levels_and_start_trims_grid():
    b = bars([[100, 100, 100, 1000, 1, 1], [100, 100, 100, 2000, 1, 1], [100, 100, 100, 1000, 1, 1]])
    out = lq.liquidation_levels(b, step=0.1, start=b.index[1])
    assert out["z"].shape[1] == 2
    assert out["z"][:, -1].sum() == pytest.approx(out["z"][:, 0].sum() / 2)


def synthetic(n=600, seed=3):
    rng = np.random.default_rng(seed)
    idx = pd.date_range(end=pd.Timestamp("2026-10-27 18:00", tz="UTC"), periods=n, freq="15min")
    c = 80000 * np.exp(np.cumsum(rng.normal(0, 0.003, n)))
    o = np.r_[c[0], c[:-1]]
    h = np.maximum(o, c) * (1 + abs(rng.normal(0, 0.001, n)))
    l = np.minimum(o, c) * (1 - abs(rng.normal(0, 0.001, n)))
    candles = pd.DataFrame({"o": o, "h": h, "l": l, "c": c, "buy": rng.uniform(50, 300, n),
                            "sell": rng.uniform(50, 300, n)}, index=idx)
    venues = {name: pd.DataFrame({"oi": base + np.cumsum(rng.normal(3, 30, n))}, index=idx)
              for name, base in (("Binance", 95000), ("Bybit", 32000), ("OKX", 31000))}
    return candles, venues


def test_combined_is_sum_of_venues():
    candles, venues = synthetic()
    start = candles.index[300]
    out = lq.combined_levels(candles, venues, start=start, step=40)
    parts = sum(v["z"] for v in out["venues"].values())
    assert np.allclose(out["z"], parts)
    assert set(out["venues"]) == {"Binance", "Bybit", "OKX"}


def test_calibration_recovers_leverage_mix(tmp_path, monkeypatch):
    """Liquidations generated by a known leverage mix: the fit should prefer
    that mix over the default one."""
    from src import storage
    from src.sources import liquidation_feeds as lf
    monkeypatch.setattr(lf, "CALIBRATION", tmp_path / "cal.json")
    candles, venues = synthetic()
    true = {5: 0.5, 25: 0.5}
    rows = []
    for name, v in venues.items():
        bars = candles[["h", "l", "c", "buy", "sell"]].assign(oi=v["oi"])
        out = lq.liquidation_levels(bars, step=lq.price_step(float(candles["c"].iloc[-1]), 0.05), leverage=true,
                                    track_removed=True)
        rows.append(out["removed"])
    rem = pd.concat(rows)
    rem = rem[rem["ts"] >= candles.index[0] + pd.Timedelta(days=2)]
    con = storage.connect(tmp_path / "m.db")
    con.executemany("INSERT OR IGNORE INTO liquidations VALUES (?,?,?,?,?,?,?)",
                    [("bybit", "BTC", r.ts.isoformat(), r.side, float(r.price), float(r.usd / r.price), float(r.usd))
                     for r in rem.itertuples()])
    con.commit()
    monkeypatch.setattr(lf, "MIN_DAYS", 1)
    monkeypatch.setattr(lf, "MIN_EVENTS", 10)
    info = lf.calibrate(con, "BTC", lambda a: (candles, venues), grid_step=0.1)
    assert info is not None
    assert info["score"] > info["default_score"]
    w = {int(k): v for k, v in info["weights"].items()}
    assert w.get(5, 0) + w.get(25, 0) > 0.7
